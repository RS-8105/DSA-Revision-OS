package com.dsarevision.dto;

import java.time.LocalDateTime;

public class RevisionHistoryResponseDto {

    private Long id;
    private Long userId;
    private Long patternId;
    private String patternName;
    private String patternCategory;
    private LocalDateTime revisionDate;
    private String confidence;
    private String notes;

    public RevisionHistoryResponseDto() {
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public Long getUserId() {
        return userId;
    }

    public void setUserId(Long userId) {
        this.userId = userId;
    }

    public Long getPatternId() {
        return patternId;
    }

    public void setPatternId(Long patternId) {
        this.patternId = patternId;
    }

    public String getPatternName() {
        return patternName;
    }

    public void setPatternName(String patternName) {
        this.patternName = patternName;
    }

    public String getPatternCategory() {
        return patternCategory;
    }

    public void setPatternCategory(String patternCategory) {
        this.patternCategory = patternCategory;
    }

    public LocalDateTime getRevisionDate() {
        return revisionDate;
    }

    public void setRevisionDate(LocalDateTime revisionDate) {
        this.revisionDate = revisionDate;
    }

    public String getConfidence() {
        return confidence;
    }

    public void setConfidence(String confidence) {
        this.confidence = confidence;
    }

    public String getNotes() {
        return notes;
    }

    public void setNotes(String notes) {
        this.notes = notes;
    }
}
